/*
Design and implement a predictive parser for a given context-free grammar (CFG) using the
LL(1) parsing technique.
The parser should perform the following tasks:
● Construct the FIRST and FOLLOW sets for the given grammar.
● Construct the LL(1) parsing table.
● Implement the predictive parsing algorithm using a stack.
● Accept an input string and determine whether it belongs to the language generated by the
grammar.
● Display the sequence of parsing steps and report whether the input string is accepted or
rejected.

*/

#include <stdio.h>
#include <string.h>

int n;
char production[100][50];

char NonTerminal[50];
int NT = 0;

char first[100][50];
int firstCount[50];

char follow[100][50];
int followCount[50];

char terminal[50];
int T = 0;
int table[50][50];

int changed;

void input_grammer() {
  printf("Number of productions? :");
  scanf("%d",&n);
  
  printf("Enter each productions (use -):\n");
  for(int i = 0;i < n;i++) {
    printf("Prod %d. ", i+1);
    scanf("%s",production[i]);
  }
}

int is_NonTerminal(char c) {
  for(int i = 0; i < NT;i++) {
    if(NonTerminal[i] == c) {
      return 1;
    }
  }
  return 0;
}

void findNT() {
  int found;
  for(int i = 0;i < n;i++) {
    found = 0;
    for(int j = 0;j < NT;j++) {
      if(production[i][0] == NonTerminal[j]) {
        found = 1;
        break;
      }
    }
    if(found == 0) {
      NonTerminal[NT++] = production[i][0];
    }
    
  }
}

void add_First(int index,char c) {
  for(int i = 0;i < firstCount[index];i++) {
    if(first[index][i] == c) {
      return;
    }
  }
  first[index][firstCount[index]] = c;
  firstCount[index]++;
}

void findFirst(char c) {
  int index = -1;
  for(int i = 0;i < NT;i++) {
    if(c == NonTerminal[i]) {
      index = i;
      break;
    }
  }
  
  
  for(int i = 0; i < n;i++) {
  
    if(production[i][0] == c) {

      for(int j = 2;production[i][j] != '\0'; j++) {
    
        char symbol = production[i][j];
        if(is_NonTerminal(symbol)) {
          findFirst(symbol);
          
          int symbolIndex = -1;
          for(int k = 0;k < NT;k++) {
            if(symbol == NonTerminal[k]) {
              symbolIndex = k;
              break;
            }
          }
             
          //epsiln      
          for(int k = 0;k < firstCount[symbolIndex];k++){
            if(first[symbolIndex][k] != 'e') {
              add_First(index,first[symbolIndex][k]);
            }
          }
          
          int has_epsilon = 0;
          for(int k = 0;k < firstCount[symbolIndex];k++) {
            if(first[symbolIndex][k] == 'e') {
              has_epsilon = 1;
              break;
            }
          }
          
          if(has_epsilon == 0) {
            break;
          }
        }
        else {
          add_First(index,symbol);
          break;
        }
      }
    }
  }
}

void add_follow(int index,char c) {
  for(int i = 0;i < followCount[index];i++) {
    if(follow[index][i] == c) {
      return;
    }
  }
  follow[index][followCount[index]] = c;
  followCount[index]++;
}

int getNTIndex(char c) {
  for(int i = 0;i < NT;i++) {
    if(c == NonTerminal[i]) {
      return i;
    } 
  }
  return -1;
}

void find_follow() {
  add_follow(0,'$');
  do{
    changed = 0;
    for(int i = 0;i < n;i++) {
      int lhsIndex = getNTIndex(production[i][0]);
      for(int j = 2;production[i][j] != '\0';j++) {
        char current = production[i][j];
        
        if(!is_NonTerminal(current)) {
          continue;
        }
        
        int currentIndex = getNTIndex(current);
        
        if(production[i][j + 1] != '\0') {
          char next = production[i][j + 1];
          if(is_NonTerminal(next)) {
            int nextIndex = getNTIndex(next);
            for(int k = 0;k < firstCount[nextIndex];k++) {
              if(first[nextIndex][k] != 'e'){
                int oldCount = followCount[currentIndex];
                add_follow(currentIndex,first[nextIndex][k]);
                if(followCount[currentIndex] > oldCount) {
                  changed = 1;
                }
              }
            }
            int hasEpsilon = 0;
            for(int k = 0;k < firstCount[nextIndex];k++) {
              if(first[nextIndex][k] == 'e') {
                hasEpsilon = 1;
                break;
              }
            }
            if(hasEpsilon) {
              for(int k = 0;k < followCount[lhsIndex];k++) {
                int oldCount = followCount[currentIndex];
                add_follow(currentIndex,follow[lhsIndex][k]);
                if(followCount[currentIndex] > oldCount) {
                  changed = 1;
                }
              }
            }
          }
          else {
            int oldCount = followCount[currentIndex];
            add_follow(currentIndex,next);
            if(followCount[currentIndex] > oldCount) {
              changed = 1;
            }
          }
        }
        else{
          for(int k = 0;k < followCount[lhsIndex];k++) {
            int oldCount = followCount[currentIndex];
            add_follow(currentIndex,follow[lhsIndex][k]);
            if(followCount[currentIndex] > oldCount) {
              changed = 1;
            }
          }
        }
        
      }
    }
  }while(changed);
}

void findTerminal() {
  int found;
  for(int i = 0;i < n;i++) {
    for(int j = 2;production[i][j] != '\0';j++) {
      char symbol = production[i][j];
      if(symbol == 'e') {
        continue;
      }
      
      if(!is_NonTerminal(symbol)) {
        found = 0;
        for(int k = 0;k < T;k++) {
          if(terminal[k] == symbol) {
            found = 1;
            break;
          }
        }
        if(found == 0) {
          terminal[T++] = symbol;
        }
      }
    }
  }
  terminal[T++] = '$';
}

int getIndex(char c) {
  for(int i = 0; i < T;i++) {
    if(terminal[i] == c) {
      return i;
    }
  }
  return -1;
}

void construct_table() {
  for(int i = 0;i < n;i++) {
    char lhs=production[i][0];
    int ntIndex = getNTIndex(lhs);
    char symbol = production[i][2];
    
    if(symbol == 'e') {
      for(int j = 0;j < followCount[ntIndex];j++) {
        int tIndex = getIndex(follow[ntIndex][j]);
        table[ntIndex][tIndex] = i; 
      }
    }
    else if(!is_NonTerminal(symbol)) {
      int tIndex = getIndex(symbol);
      table[ntIndex][tIndex] = i;
    }
    else {
      int firstIndex = getNTIndex(symbol);
      for(int j = 0;j < firstCount[firstIndex];j++) {
        if(first[firstIndex][j] != 'e'){
          int tIndex = getIndex(first[firstIndex][j]);
          table[ntIndex][tIndex] = i;
        }
      }
      int has_epsilon = 0;
      for(int j = 0;j < firstCount[firstIndex];j++) {
        if(first[firstIndex][j] == 'e') {
          has_epsilon = 1;
          break;
        }
      }
      if(has_epsilon == 1) {
        for(int j = 0;j < followCount[ntIndex];j++) {
          int tindex = getIndex(follow[ntIndex][j]);
          table[ntIndex][tindex] = i;
        }
      }
    }
  }
}

void predictiveParser() {
  char input[100],stack[100];
  int top = -1;
  int ip = 0;
  
  printf("\nEnter the INPUT string:");
  scanf("%s",input);
  printf("\n%s",input);
  int length = strlen(input);
  input[length] = '$';
  input[length + 1] = '\0';
  
  stack[++top] = '$';
  stack[++top] = NonTerminal[0];
  printf("\nStack\t\tInput\t\tAction\n");
  while(top >= 0) {
    for(int i = 0;i <= top;i++) {
      printf("%c",stack[i]);
    }
    
    printf("\t\t%s\t\t",&input[ip]);
    char X = stack[top];
    char a = input[ip];
    if(X == '$' && a == '$') {
      printf("ACCEPTED!!\n");
      return;
    }
    
    if(!is_NonTerminal(X)) {
      if(X == a) {
        printf("Matched %c\n",a);
        top--;
        ip++;
      }
      else{
        printf("ERROR!\n");
        return;
      }
    }
    else {
      int ntIndex = getNTIndex(X);
      int tIndex = getIndex(a);
      if(tIndex == -1 || table[ntIndex][tIndex] == -1) {
        printf("ERROR!\n");
        return;
      }
      int productionIndex = table[ntIndex][tIndex];
      printf("%s\n",production[productionIndex]);
      top--;
      int length = strlen(production[productionIndex]);
      for(int i = length - 1;i >= 2;i--) {
        if(production[productionIndex][i] != 'e') {
          stack[++top] = production[productionIndex][i];
        }
      }
    }
  }
  printf("Rejected");
  
}
 
 
  
int main() {
  input_grammer();
  findNT();

  for(int i = 0;i < NT;i++) {
    findFirst(NonTerminal[i]);
  }
  printf("\nFirst set\n");
  for(int i = 0;i < NT;i++) {
    printf("\n%c - {",NonTerminal[i]);
    for(int j = 0;j < firstCount[i];j++) {
      printf(" %c",first[i][j]);
    }
    printf(" }");
  }
  
  printf("\nFollow\n");
  
  find_follow();
  
  for(int i = 0;i < NT;i++) {
    printf("\n%c - {",NonTerminal[i]);
    for(int j = 0;j < followCount[i];j++) {
      printf("%c ",follow[i][j]);
    }
    printf("}");
  }
  
  findTerminal();
  for(int i = 0;i < NT;i++) {
    for(int j = 0;j < T;j++) {
      table[i][j] = -1;
    }
  }
  
  printf("\nParsing Table");
  
  construct_table();
  
  printf("\n");
  for(int i = 0;i < T;i++) {
    printf("\t%c",terminal[i]);
  }
  
  for(int i = 0;i < NT;i++) {
    printf("\n%c",NonTerminal[i]);
    for(int j = 0;j < T;j++){
      if(table[i][j] == -1) {
        printf("\t-");
      }
      else {
        printf("\t%s",production[table[i][j]]);
      }
    }
  }
  
  predictiveParser();
  return 0;
  
  
  
}

