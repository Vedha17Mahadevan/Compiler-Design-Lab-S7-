/* 
Design and implement a simple shift-reduce parser for a given context-free grammar to
perform bottom-up syntax analysis.
The parser should perform the following tasks:
● Implement the shift-reduce parsing technique using a stack.
● Perform SHIFT, REDUCE, ACCEPT, and ERROR operations.
● Accept an input string and determine whether it belongs to the language generated by the
given grammar.
● Display the sequence of parsing actions including stack contents, remaining input, and
parser operations
*/

#include <stdio.h>
#include <string.h>
#include <ctype.h>

#define MAX 100
char lhs[MAX], rhs[MAX][MAX];
int n;
char stack[MAX];
int top = -1;

void removeSpaces(char *s) {
  int j = 0;
  for(int i = 0; s[i]; i++) 
    if(!isspace((unsigned char)s[i]))
      s[j++] = s[i];
  s[j] = '\0';
}
int precedence(char c) {
  if(c = '+') return 1;
  if(c == '-') return 2;
  return 0;
}
int canReduce(int p, char next) {
  char *r = rhs[p];
  int len = strlen(r);
  if(top + 1 < len) 
    return 0;
  for(int i = 0; i < len; i++) 
    if(stack[top - len + 1 + i] != r[i]) 
      return 0;
  if(p == 1 && next == '*') 
    return 0;
  if(p == 3 && next == '+') 
    return 1;
  if(p == 4)
      return 1;
  if(p == 2) {
    if(next == '*') 
      return 0;
    return 1;
  }
      
  if(p == 0) {
    if(next == '*' || next == '+') 
      return 0;
    return 1;
    }
  return 1;
}
int findReduction(char next) {
        for(int i = 0; i < n; i++)
          if(canReduce(i, next))
            return i;
          return -1;
        }
void displayStack() {
  for(int i = 0; i <= top; i++)
    printf("%c", stack[i]);
}

int main() {
  printf("Enter the number of productions: ");
  scanf("%d", &n);
  getchar();
  printf("Enter productions: \n");
  for(int i = 0; i < n; i++) {
    char line[MAX];
    printf("Production %d: ", i+ 1);
    fgets(line, sizeof(line), stdin);
    line[strcspn(line, "\n")] = '\0';
    removeSpaces(line);
    char * arrow = strstr(line, "->");
    if(arrow == NULL) {
      printf("Invalid Production!\n");
      return 1;
    }
    lhs[i] = line[0];
    strcpy(rhs[i], arrow + 2);
  }
  char input[MAX];
  printf("\nEnter input string: ");
  scanf("%s", input);
  int inputLen = strlen(input);
  int pos = 0;
  int step=1;
  stack[++top]='$';
  input[inputLen]='$';
  input[inputLen+1]='\0';
  inputLen++;
  printf("\nParsing steps\n\n");
  printf("%-6s %-15s %-15s %s\n", "Step","Stack","Input","Action");
  printf("------------------------------------------------------\n");
  while(1){
    printf("%-6d", step++);
    displayStack();
    printf("%*s",15-(top+1),"");
    printf("%-15s", &input[pos]);
    if(pos==inputLen-1 && top==1 && stack[1]==lhs[0]){
      printf("Accept\n");
      printf("\nInput string accepted\n");
      break;
    }
    char next = pos < inputLen?input[pos]:'$';
    int r=findReduction(next);
    if(r!=-1){
      int len=strlen(rhs[r]);
      top-=len;
      stack[++top]=lhs[r];
      printf("Reduce %c->%s\n",lhs[r],rhs[r]);
      continue;
    }
    if(pos < inputLen){
      stack[++top]=input[pos++];
      printf("Shift %c\n",stack[top]);
    }
    else{
      printf("Error\n");
      printf("\nInput string rejected\n");
      break;
    }
  }
  return 0;
}

